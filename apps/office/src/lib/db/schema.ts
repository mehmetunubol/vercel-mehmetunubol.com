import {
  boolean,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";

export const presenceEnum = pgEnum("presence", ["in", "out"]);
export const conversationKindEnum = pgEnum("conversation_kind", ["direct", "group"]);

const tz = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

export const users = pgTable("users", {
  id: uuid("id").defaultRandom().primaryKey(),
  username: varchar("username", { length: 32 }).notNull().unique(),
  displayName: varchar("display_name", { length: 64 }).notNull(),
  passwordHash: text("password_hash").notNull(),
  // Bumped on password reset / change; JWTs carrying an older value are rejected.
  tokenVersion: integer("token_version").default(0).notNull(),
  // E2E identity: ECDH P-256 public key (base64 SPKI) and the matching private
  // key encrypted client-side with a key derived from the user's password.
  // Both are null until the user's first sign-in generates them.
  publicKey: text("public_key"),
  encryptedPrivateKey: text("encrypted_private_key"),
  presence: presenceEnum("presence").default("out").notNull(),
  presenceUpdatedAt: tz("presence_updated_at"),
  // A scheduled change to the opposite status ("back in 2 h", "leaving at 17:00").
  // Applied automatically once planned_at passes (see lib/presence.ts).
  plannedPresence: presenceEnum("planned_presence"),
  plannedAt: tz("planned_at"),
  plannedPrecision: varchar("planned_precision", { length: 16 }).$type<
    "exact" | "morning" | "afternoon" | "evening"
  >(),
  failedLogins: integer("failed_logins").default(0).notNull(),
  lockedUntil: tz("locked_until"),
  createdAt: tz("created_at").defaultNow().notNull(),
});

export const settings = pgTable("settings", {
  key: varchar("key", { length: 64 }).primaryKey(),
  value: text("value").notNull(),
});

export const conversations = pgTable("conversations", {
  id: uuid("id").defaultRandom().primaryKey(),
  kind: conversationKindEnum("kind").notNull(),
  name: varchar("name", { length: 64 }),
  // "<smallerUserId>:<largerUserId>" for direct chats, so each pair has one chat.
  directKey: varchar("direct_key", { length: 80 }).unique(),
  // Group where only the admin can post; members read (and react).
  announcement: boolean("announcement").default(false).notNull(),
  createdAt: tz("created_at").defaultNow().notNull(),
});

export const conversationMembers = pgTable(
  "conversation_members",
  {
    conversationId: uuid("conversation_id")
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    lastReadAt: tz("last_read_at").defaultNow().notNull(),
    joinedAt: tz("joined_at").defaultNow().notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.conversationId, t.userId] }),
    index("members_user_idx").on(t.userId),
  ],
);

export const messages = pgTable(
  "messages",
  {
    // Generated by the sender's browser and bound into the ciphertext's AAD.
    id: uuid("id").primaryKey(),
    conversationId: uuid("conversation_id")
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    senderId: uuid("sender_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    senderPublicKey: text("sender_public_key").notNull(),
    ciphertext: text("ciphertext").notNull(),
    iv: varchar("iv", { length: 32 }).notNull(),
    // recipientUserId -> base64(iv || AES-GCM-wrapped message key)
    keys: jsonb("keys").$type<Record<string, string>>().notNull(),
    createdAt: tz("created_at").defaultNow().notNull(),
    expiresAt: tz("expires_at").notNull(),
  },
  (t) => [
    index("messages_conversation_created_idx").on(t.conversationId, t.createdAt),
    index("messages_expires_idx").on(t.expiresAt),
  ],
);

export const reactionEnum = pgEnum("reaction", ["up", "down"]);

// One reaction per person per message. Stored in the clear (who reacted 👍/👎
// to which message id); the message text itself stays encrypted.
export const messageReactions = pgTable(
  "message_reactions",
  {
    messageId: uuid("message_id")
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    reaction: reactionEnum("reaction").notNull(),
    createdAt: tz("created_at").defaultNow().notNull(),
  },
  (t) => [primaryKey({ columns: [t.messageId, t.userId] })],
);

export const rsvpEnum = pgEnum("rsvp", ["pending", "going", "maybe", "declined"]);

// Events are visible only to their creator and invitees. Title and description
// are stored in the clear (unlike message text).
export const events = pgTable(
  "events",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    title: varchar("title", { length: 80 }).notNull(),
    description: varchar("description", { length: 500 }),
    startsAt: tz("starts_at").notNull(),
    durationMinutes: integer("duration_minutes").notNull(),
    createdBy: uuid("created_by")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    createdAt: tz("created_at").defaultNow().notNull(),
  },
  (t) => [index("events_starts_idx").on(t.startsAt)],
);

export const eventInvites = pgTable(
  "event_invites",
  {
    eventId: uuid("event_id")
      .notNull()
      .references(() => events.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    response: rsvpEnum("response").default("pending").notNull(),
    respondedAt: tz("responded_at"),
  },
  (t) => [
    primaryKey({ columns: [t.eventId, t.userId] }),
    index("event_invites_user_idx").on(t.userId),
  ],
);

// Shown to the admin. kind "lockout": an account was locked after too many
// failed sign-ins (userId is the account that was targeted).
export const securityAlerts = pgTable(
  "security_alerts",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    kind: varchar("kind", { length: 32 }).notNull(),
    userId: uuid("user_id").references(() => users.id, { onDelete: "cascade" }),
    createdAt: tz("created_at").defaultNow().notNull(),
    seenAt: tz("seen_at"),
  },
  (t) => [index("security_alerts_created_idx").on(t.createdAt)],
);

// Web Push endpoints, one per device that turned notifications on.
export const pushSubscriptions = pgTable(
  "push_subscriptions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    endpoint: text("endpoint").notNull().unique(),
    p256dh: varchar("p256dh", { length: 200 }).notNull(),
    auth: varchar("auth", { length: 64 }).notNull(),
    createdAt: tz("created_at").defaultNow().notNull(),
    lastSentAt: tz("last_sent_at"),
  },
  (t) => [index("push_subscriptions_user_idx").on(t.userId)],
);
