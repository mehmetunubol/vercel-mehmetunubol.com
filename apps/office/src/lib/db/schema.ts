import {
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";

export const presenceEnum = pgEnum("presence", ["in", "out"]);
export const conversationKindEnum = pgEnum("conversation_kind", ["direct", "group"]);

const tz = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

export const users = pgTable("users", {
  id: uuid("id").defaultRandom().primaryKey(),
  username: varchar("username", { length: 32 }).notNull().unique(),
  displayName: varchar("display_name", { length: 64 }).notNull(),
  passwordHash: text("password_hash").notNull(),
  // Bumped on password reset / change; JWTs carrying an older value are rejected.
  tokenVersion: integer("token_version").default(0).notNull(),
  // E2E identity: ECDH P-256 public key (base64 SPKI) and the matching private
  // key encrypted client-side with a key derived from the user's password.
  // Both are null until the user's first sign-in generates them.
  publicKey: text("public_key"),
  encryptedPrivateKey: text("encrypted_private_key"),
  presence: presenceEnum("presence").default("out").notNull(),
  presenceUpdatedAt: tz("presence_updated_at"),
  failedLogins: integer("failed_logins").default(0).notNull(),
  lockedUntil: tz("locked_until"),
  createdAt: tz("created_at").defaultNow().notNull(),
});

export const settings = pgTable("settings", {
  key: varchar("key", { length: 64 }).primaryKey(),
  value: text("value").notNull(),
});

export const conversations = pgTable("conversations", {
  id: uuid("id").defaultRandom().primaryKey(),
  kind: conversationKindEnum("kind").notNull(),
  name: varchar("name", { length: 64 }),
  // "<smallerUserId>:<largerUserId>" for direct chats, so each pair has one chat.
  directKey: varchar("direct_key", { length: 80 }).unique(),
  createdAt: tz("created_at").defaultNow().notNull(),
});

export const conversationMembers = pgTable(
  "conversation_members",
  {
    conversationId: uuid("conversation_id")
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    lastReadAt: tz("last_read_at").defaultNow().notNull(),
    joinedAt: tz("joined_at").defaultNow().notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.conversationId, t.userId] }),
    index("members_user_idx").on(t.userId),
  ],
);

export const messages = pgTable(
  "messages",
  {
    // Generated by the sender's browser and bound into the ciphertext's AAD.
    id: uuid("id").primaryKey(),
    conversationId: uuid("conversation_id")
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    senderId: uuid("sender_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    senderPublicKey: text("sender_public_key").notNull(),
    ciphertext: text("ciphertext").notNull(),
    iv: varchar("iv", { length: 32 }).notNull(),
    // recipientUserId -> base64(iv || AES-GCM-wrapped message key)
    keys: jsonb("keys").$type<Record<string, string>>().notNull(),
    createdAt: tz("created_at").defaultNow().notNull(),
    expiresAt: tz("expires_at").notNull(),
  },
  (t) => [
    index("messages_conversation_created_idx").on(t.conversationId, t.createdAt),
    index("messages_expires_idx").on(t.expiresAt),
  ],
);
